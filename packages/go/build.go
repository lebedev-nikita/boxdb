//go:build ignore

// Build the native library and invalidate Go's cgo cache when its contents change.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
)

func main() {
	if err := build(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func build() error {
	release := flag.Bool("release", false, "build an optimized native library")
	flag.Parse()
	_, source, _, _ := runtime.Caller(0)
	module := filepath.Dir(source)
	manifest := filepath.Join(module, "..", "..", "Cargo.toml")
	args := []string{"build", "--locked", "--manifest-path", manifest, "-p", "boxdb-go"}
	profile := "debug"
	if *release {
		args = append(args, "--release")
		profile = "release"
	}
	command := exec.Command("cargo", args...)
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	if err := command.Run(); err != nil {
		return err
	}
	metadata, err := exec.Command("cargo", "metadata", "--no-deps", "--format-version", "1", "--manifest-path", manifest).Output()
	if err != nil {
		return err
	}
	var workspace struct {
		TargetDirectory string `json:"target_directory"`
	}
	if err := json.Unmarshal(metadata, &workspace); err != nil {
		return err
	}
	library, err := os.Open(filepath.Join(workspace.TargetDirectory, profile, "libboxdb_go.a"))
	if err != nil {
		return err
	}
	defer library.Close()
	directory := filepath.Join(module, "native", "lib")
	if err := os.MkdirAll(directory, 0755); err != nil {
		return err
	}
	output, err := os.Create(filepath.Join(directory, "libboxdb_go.a"))
	if err != nil {
		return err
	}
	hash := sha256.New()
	_, copyErr := io.Copy(io.MultiWriter(output, hash), library)
	closeErr := output.Close()
	if copyErr != nil {
		return copyErr
	}
	if closeErr != nil {
		return closeErr
	}
	generated := fmt.Sprintf("// Code generated by build.go; DO NOT EDIT.\n\npackage boxdb\n\nconst nativeBuildID = %q\n", fmt.Sprintf("%x", hash.Sum(nil)))
	return os.WriteFile(filepath.Join(module, "native_build.go"), []byte(generated), 0644)
}
