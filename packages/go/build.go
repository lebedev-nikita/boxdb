//go:build ignore

// Build the native library and invalidate Go's cgo cache when its contents change.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

func main() {
	if err := build(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func build() error {
	release := flag.Bool("release", false, "build an optimized native library")
	flag.Parse()
	_, source, _, _ := runtime.Caller(0)
	module := filepath.Dir(source)
	manifest := filepath.Join(module, "..", "..", "Cargo.toml")
	args := []string{"build", "--locked", "--manifest-path", manifest, "-p", "boxdb-go"}
	profile := "debug"
	if *release {
		args = append(args, "--release")
		profile = "release"
	}
	command := exec.Command("cargo", args...)
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	if err := command.Run(); err != nil {
		return err
	}
	metadata, err := exec.Command("cargo", "metadata", "--no-deps", "--format-version", "1", "--manifest-path", manifest).Output()
	if err != nil {
		return err
	}
	var workspace struct {
		TargetDirectory string `json:"target_directory"`
	}
	if err := json.Unmarshal(metadata, &workspace); err != nil {
		return err
	}
	library, err := os.Open(filepath.Join(workspace.TargetDirectory, profile, "libboxdb_go.a"))
	if err != nil {
		return err
	}
	defer library.Close()
	directory := filepath.Join(module, "native", "lib")
	if err := os.MkdirAll(directory, 0755); err != nil {
		return err
	}
	path := filepath.Join(directory, "libboxdb_go.a")
	output, err := os.Create(path)
	if err != nil {
		return err
	}
	_, copyErr := io.Copy(output, library)
	closeErr := output.Close()
	if copyErr != nil {
		return copyErr
	}
	if closeErr != nil {
		return closeErr
	}
	if err := stripBitcode(path); err != nil {
		return err
	}
	contents, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	generated := fmt.Sprintf("// Code generated by build.go; DO NOT EDIT.\n\npackage boxdb\n\nconst nativeBuildID = %q\n", fmt.Sprintf("%x", sha256.Sum256(contents)))
	return os.WriteFile(filepath.Join(module, "native_build.go"), []byte(generated), 0644)
}

// stripBitcode removes LLVM bitcode that Rust's prebuilt standard library
// embeds in its objects. Recent Go releases reject cgo libraries containing
// LTO sections; the system linker never reads them.
func stripBitcode(path string) error {
	sysroot, err := exec.Command("rustc", "--print", "sysroot").Output()
	if err != nil {
		return err
	}
	version, err := exec.Command("rustc", "-vV").Output()
	if err != nil {
		return err
	}
	host := ""
	for _, line := range strings.Split(string(version), "\n") {
		if value, ok := strings.CutPrefix(line, "host: "); ok {
			host = strings.TrimSpace(value)
		}
	}
	objcopy := filepath.Join(strings.TrimSpace(string(sysroot)), "lib", "rustlib", host, "bin", "llvm-objcopy")
	if runtime.GOOS == "windows" {
		objcopy += ".exe"
	}
	if _, err := os.Stat(objcopy); err != nil {
		return fmt.Errorf("llvm-objcopy is required to strip LLVM bitcode; install it with `rustup component add llvm-tools`: %w", err)
	}
	command := exec.Command(objcopy, "--wildcard", "--remove-section=__LLVM,*", "--remove-section=.llvmbc", "--remove-section=.llvmcmd", path)
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	return command.Run()
}
